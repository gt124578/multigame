function cedilla(ch, base) {
  const b = G[base], rows = b.rows.slice(), c = Math.floor(b.w / 2);
  const r9 = rows[9].split(''), r10 = rows[10].split('');
  r9[c] = '#'; if (c > 0) r10[c - 1] = '#';
  rows[9] = r9.join(''); rows[10] = r10.join('');
  G[ch] = { w: b.w, rows };
}
