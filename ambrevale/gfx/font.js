export const LINE_H = 11;

export function glyph(ch) { return G[ch] || G['?']; }

export function textWidth(str) {
  let w = 0;
  for (const ch of str) w += glyph(ch).w + 1;
  return Math.max(0, w - 1);
}

/** Dessine du texte pixel par pixel. color = couleur principale, shadow = ombre (ou null). */
export function drawText(ctx, str, x, y, color = '#484850', shadow = '#d0d0c8') {
  x = Math.round(x); y = Math.round(y);
  const pass = (col, dx, dy) => {
    ctx.fillStyle = col;
    let cx = x;
    for (const ch of str) {
      const g = glyph(ch);
      for (let r = 0; r < 11; r++) {
        const row = g.rows[r];
        for (let c = 0; c < g.w; c++) if (row[c] === '#') ctx.fillRect(cx + c + dx, y + r + dy, 1, 1);
      }
      cx += g.w + 1;
    }
  };
  if (shadow) { pass(shadow, 1, 0); pass(shadow, 0, 1); pass(shadow, 1, 1); }
  pass(color, 0, 0);
  return textWidth(str);
}

export function drawTextCentered(ctx, str, cx, y, color, shadow) {
  return drawText(ctx, str, cx - textWidth(str) / 2, y, color, shadow);
}
export function drawTextRight(ctx, str, rx, y, color, shadow) {
  return drawText(ctx, str, rx - textWidth(str), y, color, shadow);
}

/** Coupe un texte en lignes qui tiennent dans maxW pixels (respecte les \n). */
export function wrap(str, maxW) {
  const out = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (textWidth(t) <= maxW || !line) line = t; else { out.push(line); line = word; }
    }
    out.push(line);
  }
  return out;
}
