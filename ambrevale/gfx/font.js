const ACC = {
  acute: ['..#', '.#.'], grave: ['#..', '.#.'], circ: ['.#.', '#.#'], diaer: ['...', '#.#'],
};
function compose(ch, base, acc, upper) {
  const b = G[base];
  let w = Math.max(b.w, 3);
  const off = Math.floor((w - b.w) / 2);
  const rows = b.rows.map((r) => ('.'.repeat(off) + r).padEnd(w, '.'));
  const a = ACC[acc], ao = Math.floor((w - 3) / 2) + (b.w % 2 === 0 && w > 3 ? 0 : 0);
  const r0 = upper ? 0 : 2;
  for (let k = 0; k < 2; k++) {
    const line = rows[r0 + k].split('');
    // i sans point quand il porte un accent
    if (!upper && base === 'i') for (let x = 0; x < w; x++) line[x] = '.';
    for (let x = 0; x < 3; x++) if (a[k][x] === '#') line[ao + x] = '#';
    rows[r0 + k] = line.join('');
  }
  G[ch] = { w, rows };
}
