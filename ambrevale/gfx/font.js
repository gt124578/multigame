const G = {}; // caractère -> { w, rows: string[11] }

function def(ch, rows9) {
  const rows = rows9.split('/');
  const w = Math.max(...rows.map((r) => r.length));
  const pad = (r) => r.padEnd(w, '.');
  while (rows.length < 9) rows.push('');
  G[ch] = { w, rows: ['', ''].concat(rows.slice(0, 9)).map(pad) };
}

